import {readFileSync,writeFileSync} from 'node:fs';
import {execFileSync} from 'node:child_process';
import assert from 'node:assert/strict';
import {runtimePolicy} from './runtime-policy.mjs';
const versions=JSON.parse(readFileSync(new URL('../versions/index.json',import.meta.url))).versions.map(x=>x.version);
const mapped=Object.values(runtimePolicy).flatMap(x=>x.versions);
assert.deepEqual([...mapped].sort(),[...versions].sort());
assert.equal(new Set(mapped).size,mapped.length);
let source='// Code generated by compiler/vyper/wasm/generate-policy.mjs; DO NOT EDIT.\npackage verify\n\ntype vyperRuntimeSpec struct { ID, Pyodide, Python, Pycryptodome, SharedSHA256, Version string }\n\nvar vyperRuntimeSpecs = map[string]vyperRuntimeSpec{\n';
for(const [id,p] of Object.entries(runtimePolicy)) {
 assert.match(p.shared_sha256,/^[a-f0-9]{64}$/); assert.notEqual(p.shared_sha256,'0'.repeat(64));
 source+=`${JSON.stringify(id)}: {${[id,p.pyodide,p.python,p.pycryptodome,p.shared_sha256,p.versions[0]].map(JSON.stringify).join(',')}},\n`;
}
source+='}\n\nvar vyperVersionRuntime = map[string]string{\n';
for(const [id,p] of Object.entries(runtimePolicy)) for(const version of p.versions) source+=`${JSON.stringify(version)}: ${JSON.stringify(id)},\n`;
source+='}\n';
const output=new URL('../../../internal/verify/vyper_runtime_policy_generated.go',import.meta.url);
writeFileSync(output,execFileSync('gofmt',{input:source}));
